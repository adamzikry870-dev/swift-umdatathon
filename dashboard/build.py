    baseline_note(fig, 0.625, 0.320,
                  "a single geometric law fitted to the two-bank share and extended across the tail")

    strip(fig, "Chains lengthen only when an intermediary is genuinely required, so long chains are rare "
               "by construction, not by policy. Conversion is a corridor property: a euro-zone payment "
               "never needs an FX desk, a dollar payment into Asia almost always does.")
    return save(fig, "06_chain", pdf)


