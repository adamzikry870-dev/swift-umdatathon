# ------------------------------------------------------- group 1, when payments
def page_time(pdf=None):
    curves = read("hour_curves", index_col=0)
    total = curves.sum(axis=1)
    keep = total[total >= 5000].index
    m = curves.loc[keep].values.astype(float)
    m = m / m.sum(axis=1, keepdims=True)
    ref = m.sum(axis=0)
    ref = ref / ref.sum()

    aligned = []
    for v in m:
        shift = max(((float(np.corrcoef(np.roll(v, s), ref)[0, 1]), s) for s in range(24)))[1]
        aligned.append(np.roll(v, shift))
    A = np.mean(aligned, axis=0)
    A = np.roll(A, -int(np.argmax(A)))
    U = m.mean(axis=0)
    U = np.roll(U, -int(np.argmax(U)))

    before = _pairwise(m)
    after = _pairwise(np.vstack(aligned))
    meta = jload("hour_meta.json")

    daily = read("daily_volume")
    weekend = daily.loc[daily.dow >= 5, "n"].sum() / daily.n.sum()

    fig = new_page(3, "Group 1 of 8  \u00b7  When payments happen",
                   "Payments follow the sun, not a global clock",
                   "Each country runs the same working-day template: a sharp morning peak and a "
                   "second hump after lunch, stamped on its own whole-hour clock.")

    ax = axes_at(fig, [0.075, 0.205, 0.520, 0.578])
    h = np.arange(24)
    ax.plot(h, U * 100, color=S.GOLD, lw=1.9, ls="--",
            label="the same data on one global clock")
    ax.plot(h, A * 100, color=S.NAVY, lw=2.7,
            label="each country on its own clock")
    ax.axhline(100 / 24, color=S.GREY, lw=1.1, ls=":",
               label="a flat day (4.2% an hour)")
    ax.set_xlim(-0.5, 23.5)
    ax.set_ylim(0, 9.2)
    ax.set_xticks([0, 3, 6, 9, 12, 15, 18, 21])
    ax.set_xlabel("hours from the busiest hour of the day")
    ax.set_ylabel("share of payments in that hour (%)")
    ax.legend(loc="upper right", fontsize=7.8, frameon=False,
              handlelength=2.2, borderaxespad=0.6)
    top = int(np.argmax(A))
    ax.annotate(f"{A.max()*100:.1f}% in the peak hour",
                (top, A.max() * 100), xytext=(top + 3.4, A.max() * 100 + 0.9),
                fontsize=8.4, color=S.NAVY,
                arrowprops=dict(arrowstyle="-", color=S.NAVY, lw=0.8))
    five = np.sort(A)[-5:].sum() * 100
    ax.text(0.985, 0.055, f"{five:.0f}% of the day falls in five hours",
            transform=ax.transAxes, ha="right", fontsize=8.4, color=S.MUTED,
            style="italic")
    S.clean(ax)
    caption(ax, "Mean of the 113 country curves, each put on its own busiest hour, "
                "against the same curves left on one clock")

    stat(fig, 0.625, 0.792, f"{before:.2f} \u2192 {after:.2f}",
         "agreement between the 113 country curves, before and after alignment")
    stat(fig, 0.625, 0.700, f"{meta['offsets']}",
         "distinct whole-hour clocks carry all 113 markets")
    stat(fig, 0.625, 0.608, f"{weekend*100:.1f}%",
         "of volume arrives at the weekend, against 28.6% if every day were equal")

    rule_block(fig, 0.625, 0.548, [
        ("CONDITION", "any sender market, any day of the week"),
        ("EFFECT", "the hour is drawn from one shared two-humped template, then shifted by a whole number of hours"),
        ("SCOPE", "113 markets with 5,000+ payments, on weekdays and weekends alike"),
    ])
    baseline_note(fig, 0.625, 0.320,
                  "the same 113 curves kept on a single global clock, and a flat day at 4.2% an hour")

    strip(fig, "Settlement follows local banking hours. A global peak is the hour when many local "
               "business days overlap: a treasury clock, not a market clock. Weekends collapse because "
               "treasuries do not initiate on Saturdays.")
    return save(fig, "02_when", pdf)


def _pairwise(mat):
    corr = np.corrcoef(mat)
    k = len(mat)
    return float((corr.sum() - np.trace(corr)) / (k * (k - 1)))


# ------------------------------------------------------------ group 2, currency
def page_currency(pdf=None):
    share = read("currency_local_share")
    weight = share.local.sum() / share.n.sum()
    market = share[share.n >= 5000].sort_values("local_share").reset_index(drop=True)
    short = (1 - market.local_share) * 100
    mix = read("currency_foreign_mix")
    eur = mix.loc[mix.currency == "EUR", "payments"].iloc[0] / mix.payments.sum()
    usd = mix.loc[mix.currency == "USD", "payments"].iloc[0] / mix.payments.sum()

    fig = new_page(4, "Group 2 of 8  \u00b7  Which currency",
                   "Payers pay in their own currency, and there is no FX desk in this file",
                   "The currency is a sender-side choice. The 6.6% that are foreign lean to the euro "
                   "and the dollar, and amounts are stated in one unit, so no conversion leg is priced.")

    ax = axes_at(fig, [0.085, 0.205, 0.505, 0.578])
    y = np.arange(len(market))
    ax.barh(y, short.values, height=1.0, color=S.NAVY, linewidth=0)
    ax.set_xlim(0, 30)
    ax.set_ylim(len(market) - 0.2, -4.2)
    ax.set_yticks([])
    ax.set_xlabel("percentage points below 100% home-currency billing")
    line = (1 - weight) * 100
    ax.axvline(line, color=S.GOLD, lw=1.6, ls="--", zorder=4)
    ax.text(line + 0.7, -2.6, f"all 228 markets, volume-weighted: {weight*100:.1f}% at home",
            fontsize=8.2, color=S.GOLD, va="center", fontweight="bold")
    ax.text(len(market) - 0.6, short.iloc[0] + 0.1,
            f"{market.oc.iloc[0]}  {market.local_share.iloc[0]*100:.1f}%",
            fontsize=7.6, color=S.BODY, va="center", ha="right")
    ax.text(len(market) - 0.6, len(market) - 1.1,
            f"{market.oc.iloc[-1]}  {market.local_share.iloc[-1]*100:.1f}%",
            fontsize=7.6, color=S.BODY, va="center", ha="right")
    S.clean(ax, "x")
    caption(ax, "One bar per sender market, ranked by shortfall; 113 markets with 5,000+ payments")

    stat(fig, 0.625, 0.792, f"{weight*100:.1f}%",
         "of payments are in the home currency of the sending market")
    stat(fig, 0.625, 0.700, "73% to 98%",
         "the full range across those 113 markets; none bills entirely at home")
    stat(fig, 0.625, 0.608, f"{eur*100:.0f}%",
         f"of the foreign 6.6% are euros, a further {usd*100:.0f}% dollars")

    rule_block(fig, 0.625, 0.548, [
        ("CONDITION", "the sender's market, not the corridor"),
        ("EFFECT", "the currency is that market's home currency; the foreign residual leans to EUR, then USD"),
        ("SCOPE", "113 markets, 73% to 98% local; no payment carries a separable FX leg"),
    ])
    baseline_note(fig, 0.625, 0.320,
                  "100% home-currency billing, which every market falls short of by 2 to 27 points")

    strip(fig, "A payer books the ticket in its own currency and leaves conversion to the correspondent, "
               "so FX is priced into the amount rather than settled as a separate leg. Any implied rate "
               "computed from this file is an artefact.")
    return save(fig, "03_currency", pdf)


