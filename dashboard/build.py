    ax = axes_at(fig, [0.072, 0.205, 0.512, 0.578])
    ax.axvspan(10.5, 23.4, color=S.TINT, zorder=0)
    ax.plot(fit_k, pred, color=S.GOLD, lw=1.6, ls="--", zorder=2,
            label="one rule: 0.632 x 0.368 per extra bank")
    ax.plot(k, obs, "o", ms=6.5, color=S.NAVY, zorder=3, label="observed")
    ax.set_yscale("log")
    ax.set_xticks([2, 3, 4, 5, 6, 7, 8, 9, 10, 12, 14, 16, 18, 20, 22])
