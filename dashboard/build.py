def page_anomaly(pdf=None):
    raw = read("anomaly_by_beneficiary_country")
    raw["per100k"] = raw.rate * 1e5
    pool = raw[raw.total >= 2000]
    top = pool.sort_values("per100k", ascending=False).head(12)
    us = pool[pool.bc == "US"]
    table = pd.concat([top, us]).drop_duplicates("bc").reset_index(drop=True)
    overall = 7006 / 10_000_000 * 1e5

    def short_n(x):
        if x >= 1e6:
            return f"{x/1e6:.1f}m"
        if x >= 1e3:
            return f"{x/1e3:.1f}k"
        return f"{x:.0f}"

    fig = new_page(10, "Group 8 of 8  \u00b7  What goes wrong",
                   "Seven thousand flags, and the rate belongs to the destination",
                   "Each label is a distinct mechanism, not a severity score. Where a payment lands sets how "
                   "often it is flagged, from 33 per 100,000 in the United States to 7,914 in Pakistan.")

    ax = axes_at(fig, [0.098, 0.205, 0.495, 0.578])
    y = np.arange(len(table))
    colors = [S.CORAL if c == "US" else S.NAVY for c in table.bc]
    ax.scatter(table.per100k, y, s=62, c=colors, zorder=3,
               edgecolor="white", linewidth=0.7)
    ax.set_xscale("log")
    ax.set_yticks(y)
    ax.set_yticklabels([f"{r.bc}  \u00b7  {short_n(r.total)}" for r in table.itertuples()],
                       fontsize=8.2)
    for tick, col in zip(ax.get_yticklabels(), colors):
        tick.set_color(col)
    ax.set_xlim(20, 20000)
    ax.set_ylim(len(table) - 0.4, -1.1)
    ax.axvline(overall, color=S.GOLD, lw=1.5, ls="--", zorder=2)
    for i, v in enumerate(table.per100k):
        ax.text(v * 1.20, i, f"{v:,.0f}", va="center", fontsize=7.6, color=S.MUTED)
    ax.text(overall * 1.08, -0.75, f"file average {overall:.0f} per 100k",
            fontsize=8.0, color=S.GOLD, fontweight="bold", va="center")
    ax.set_xlabel("labelled anomalies per 100,000 payments (log scale)")
    S.clean(ax, "x")
    caption(ax, "Destination countries with 2,000+ payments, ranked; label shows the payment count")

    stat(fig, 0.625, 0.792, "7,006",
         "flagged rows, 0.07% of the file, across six distinct labels")
    stat(fig, 0.625, 0.700, "56%",
         "of fat-finger rows return to a normal amount when divided by 100 or 1,000")
    stat(fig, 0.625, 0.608, "33 to 7,914",
         "flags per 100,000, United States against Pakistan")

    rule_block(fig, 0.625, 0.548, [
        ("CONDITION", "an anomaly label, and the route that payment took"),
        ("EFFECT", "each label is its own mechanism: three scams avoid covered routes, three errors do not"),
        ("SCOPE", "7,006 rows, 0.07% of the file; the rate runs from 33 to 7,914 per 100,000"),
    ])
    baseline_note(fig, 0.625, 0.320,
                  "the file-wide rate of 70 flags per 100,000 payments, which most destinations sit far from")

    strip(fig, "Two thousand four hundred and seventy-six rows are romance scams, 1,940 fat-finger slips, "
               "945 CEO scams, 679 duplicates, 649 account replacements, 317 recalls. Three are social "
               "engineering and three are operational error, which is why they differ in route mix.")
    return save(fig, "09_anomaly", pdf)


