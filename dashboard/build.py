# ----------------------------------------------------------------- page furniture
def new_page(number, kicker, title, claim=None):
    fig = plt.figure(figsize=PAGE)
    fig.patch.set_facecolor(S.BG)
    fig.text(0.048, 0.958, kicker.upper(), fontsize=8.0, color=S.TEAL,
             fontweight="bold", va="top")
    fig.text(0.048, 0.922, title, fontsize=17.0, color=S.NAVY,
             fontweight="bold", va="top")
    if claim:
        fig.text(0.048, 0.862, textwrap.fill(claim, 168), fontsize=9.8,
                 color=S.BODY, va="top", linespacing=1.45)
    foot(fig, number)
    return fig


def foot(fig, number):
    fig.text(0.048, 0.036, "UM Datathon 2026  \u00b7  Swift case study",
             fontsize=7.2, color=S.MUTED)
    fig.text(0.500, 0.036, "synthetic data", fontsize=7.2, color=S.MUTED, ha="center")
    fig.text(0.952, 0.036, f"{number:02d} / {TOTAL}", fontsize=7.2,
             color=S.MUTED, ha="right")


def strip(fig, text):
    fig.patches.append(Rectangle((0.048, 0.072), 0.904, 0.060,
                                 transform=fig.transFigure, facecolor=S.TINT,
                                 edgecolor="none", zorder=-5))
    fig.patches.append(Rectangle((0.048, 0.072), 0.005, 0.060,
                                 transform=fig.transFigure, facecolor=S.GOLD,
                                 edgecolor="none", zorder=-4))
    fig.text(0.064, 0.102, textwrap.fill(text, 190), fontsize=8.5,
             color=S.BODY, va="center", linespacing=1.35)


def stat(fig, x, y, value, label, color=S.NAVY):
    fig.text(x, y, value, fontsize=19.5, color=color, fontweight="bold", va="top")
    fig.text(x, y - 0.040, textwrap.fill(label, 52), fontsize=7.8, color=S.MUTED,
             va="top", linespacing=1.32)


def rule_block(fig, x, y, rows):
    fig.text(x, y, "THE RULE", fontsize=6.8, color=S.GOLD, fontweight="bold")
    yy = y - 0.030
    for label, text in rows:
        lines = textwrap.wrap(text, 66)
        fig.text(x, yy, label, fontsize=6.6, color=S.MUTED, fontweight="bold")
        fig.text(x, yy - 0.019, "\n".join(lines), fontsize=7.9, color=S.BODY,
                 va="top", linespacing=1.32)
        yy -= 0.019 + 0.0190 * len(lines) + 0.020


def baseline_note(fig, x, y, text):
    fig.text(x, y, "COMPARED AGAINST", fontsize=6.6, color=S.GOLD, fontweight="bold")
    fig.text(x, y - 0.020, textwrap.fill(text, 66), fontsize=7.9, color=S.BODY,
             va="top", linespacing=1.32)


def axes_at(fig, rect):
    return fig.add_axes(rect)


def caption(ax, text):
    ax.set_title(text, loc="left", fontsize=8.2, color=S.MUTED, pad=9)


